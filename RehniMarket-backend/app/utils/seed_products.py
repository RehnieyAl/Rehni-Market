def build_extra_companies():
    """Construye la lista de empresas y productos ampliados en el mismo formato que
    `COMPANIES` de `app/utils/seed.py`."""

    from app.utils import seed as S

    rng = random.Random(20260901)

    companies = [
        {
            "name": name, "email": email, "nit": nit, "dv": dv,
            "address": address, "description": description, "products": [],
        }
        for name, email, nit, dv, address, description in COMPANY_DEFS
    ]

    counter = 0
    for config in _catalog_configs(S):
        axes = config["axes"]
        code = config["code"]
        warranty = config["warranty"]
        noun = config["noun"]
        blurb = config["blurb"]
        tint = config["tint"]
        applies_tax = config.get("applies_tax", True)

        for brand, model, base_price, specs in config["items"]:
            counter += 1
            name = f"{noun} {brand} {model}"[:100]
            product = {
                "name": name,
                "catalog": config["catalog"],
                "descripcion": f"{brand} {model}. {blurb}",
                "price": base_price,
                "image": tint,
                "applies_tax": applies_tax,
                "specs": {"Marca": brand, "Modelo": model, "Garantía": warranty, **specs},
                "variants": _build_variants(code, counter, base_price, axes, rng),
            }
            if counter % 9 == 0:
                product["discount"] = _pct(rng.choice([5, 8, 10, 12, 15, 20]))

            companies[counter % len(companies)]["products"].append(product)

    return companies
